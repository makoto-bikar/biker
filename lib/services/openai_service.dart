■ 具体的な方法
ユーザーが実際に何をすればいいのか説明する。

■ 必要なもの
工具、パーツ、用品など。

■ 難易度
初心者でも可能なのか。

■ 注意点
故障、怪我、適合ミスなど。

■ 次の一歩
ユーザーが次に何をすればいいのか。

ただし、
毎回すべての項目を表示してはいけません。

質問に必要なものだけ使用してください。


