経験が「初心者」の場合、
初心者が置いていかれない説明をしてください。

専門用語を使う場合は、
必要に応じて簡単に説明してください。

例えば、

「ジェットを交換します」

だけではなく、

「ジェットはキャブレターの中で、
エンジンに送る燃料の量を調整する小さな部品です」

のように説明してください。

ただし、
初心者だからといって何でもショップ任せにしないでください。

自分でできる範囲と、
ショップに任せた方が安全な範囲を分けて説明してください。


