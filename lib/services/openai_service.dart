    });


    // ========================================================
    // 会話履歴
    // ========================================================

    if (conversationId != null) {
      final history =
          await firestore.getConversationMessages(
        conversationId,
      );


      // ======================================================
      // 最新20メッセージ
      // ======================================================

      final recentHistory =
          history.length > 20
              ? history.sublist(
                  history.length - 20,
                )
              : history;


      // ======================================================
      // 今回の質問がすでにFirestoreに保存されている場合、
      // 最新の重複だけを履歴から除外する。
      // ======================================================

      bool skippedCurrentMessage = false;


      for (int i = recentHistory.length - 1;
          i >= 0;
          i--) {
        final chat = recentHistory[i];

        final chatText =
            chat["text"]?.toString() ?? "";

        final isUser =
            chat["isUser"] == true;


        // -----------------------------------------------
        // 今回送信した質問と同じユーザーメッセージが
        // Firestoreに保存されていたら1件だけ除外
        // -----------------------------------------------

        if (!skippedCurrentMessage &&
            isUser &&
            chatText.trim() ==
                message.trim()) {
          skippedCurrentMessage = true;
          continue;
        }


        messages.add({
          "role": isUser
              ? "user"
              : "assistant",

          "content": chatText,
        });
      }
    }


    // ========================================================
    // 今回の質問
    // ========================================================

    messages.add({
      "role": "user",
      "content": message,
    });


    // ========================================================
    // OpenAI API
    // ========================================================

    try {
      final response = await http.post(
        Uri.parse(
          "https://api.openai.com/v1/chat/completions",
        ),

        headers: {
          "Authorization":
              "Bearer $apiKey",

          "Content-Type":
              "application/json",
        },

        body: jsonEncode({
          "model": "gpt-4.1-mini",

          "messages": messages,

          "response_format": {
            "type": "json_object",
          },

          // --------------------------------------------------
          // 回答が短くなりすぎないようにする。
          // ただしプロンプト側で質問内容に応じて
          // 長さを調整するよう指定している。
          // --------------------------------------------------

          "temperature": 0.7,

          "max_tokens": 2500,
        }),
      );


      // ======================================================
      // API成功
      // ======================================================

      if (response.statusCode == 200) {
        final data = jsonDecode(response.body);


        final content =
            data["choices"]?[0]?["message"]?["content"]
                ?.toString() ??
            "";


        if (content.isEmpty) {
          return AIResponse(
            answer:
                "AIから回答を取得できませんでした。",
            products: [],
          );
        }


        // ====================================================
        // JSON解析
        // ====================================================

        try {
          final json = jsonDecode(content);


          final answer =
              json["answer"]?.toString() ?? "";


          final productData =
              json["products"];


          List<ProductRecommendation> products = [];


          // ==================================================
          // 商品データ処理
          // ==================================================

          if (productData is List) {
            products = productData
                .whereType<Map>()
                .map(
                  (item) {
                    return ProductRecommendation
                        .fromJson(
                      Map<String, dynamic>.from(
                        item,
                      ),
                    );
                  },
                )
                .where(
                  (product) =>
                      product.name.isNotEmpty,
                )
                .take(3)
                .toList();
          }


          // ==================================================
          // AIResponse
          // ==================================================

          return AIResponse(
            answer:
                answer.isNotEmpty
                    ? answer
                    : "回答を取得できませんでした。",
            products: products,
          );
        } catch (e) {
          // ==================================================
          // JSON解析失敗
          // ==================================================

          return AIResponse(
            answer: content,
            products: [],
          );
        }
      }


      // ======================================================
      // APIエラー
      // ======================================================

      String errorMessage =
          "AIとの通信でエラーが発生しました。";


      try {
        final errorData =
            jsonDecode(response.body);


        final apiError =
            errorData["error"]?["message"]
                ?.toString();


        if (apiError != null &&
            apiError.isNotEmpty) {
          errorMessage =
              "AIとの通信でエラーが発生しました。\n"
              "$apiError";
        }
      } catch (_) {
        // エラー本文のJSON解析に失敗した場合は
        // デフォルトメッセージを使用
      }


      return AIResponse(
        answer: errorMessage,
        products: [],
      );
    } catch (e) {
      // ======================================================
      // 通信そのものに失敗
      // ======================================================

      return AIResponse(
        answer:
            "AIとの通信に失敗しました。\n"
            "ネットワーク接続を確認してください。",
        products: [],
      );
    }
  }
